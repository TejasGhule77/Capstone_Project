  static String get(String key, String lang) {
    final map = _translations[key];
    if (map == null) return key;
    return map[lang] ?? map['mr'] ?? map['en'] ?? key;
  }

  static String cropName(String crop, String lang) {
    final lower = crop.toLowerCase();
    if (lower.contains('grape')) return get('crop_grapes', lang);
    if (lower.contains('onion')) return get('crop_onion', lang);
    if (lower.contains('sugar')) return get('crop_sugarcane', lang);
    if (lower.contains('wheat')) return get('crop_wheat', lang);
    return crop;
  }
